import {
  DocumentSource,
  VerificationAttempt,
  WeaknessCategory,
} from '../types/game';

export interface QuoteVerificationOutput {
  verified: boolean;
  matchType: 'EXACT_SUBSTRING' | 'NORMALIZED_VERBATIM' | 'HALLUCINATION_REJECTED';
  matchScore: number;
  matchedLocation: string;
  matchedCharIndex: number;
  canonicalQuote: string;
  surroundingContext: string;
  statusMessage: string;
}

function normalizeTextForComparison(input: string): string {
  return input
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/-\s*\n\s*/g, '') // PDF line-break hyphenation
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/**
 * Strict Citation Verification Loop:
 * Checks whether a candidate quote generated by Reviewer 2 actually exists verbatim
 * inside the uploaded manuscript or GitHub repository corpus.
 * If not found, it is flagged as HALLUCINATION_REJECTED and discarded.
 */
export function verifyQuoteInDocument(
  candidateQuote: string,
  doc: DocumentSource
): QuoteVerificationOutput {
  const cleanedCandidate = candidateQuote.trim().replace(/^["'“”]+|["'“”]+$/g, '').trim();

  if (cleanedCandidate.length < 12) {
    return {
      verified: false,
      matchType: 'HALLUCINATION_REJECTED',
      matchScore: 0.12,
      matchedLocation: 'N/A',
      matchedCharIndex: -1,
      canonicalQuote: cleanedCandidate,
      surroundingContext: '',
      statusMessage: 'Rejected: Quote is too short or not a concrete sentence from the manuscript (min 12 chars required).',
    };
  }

  // 1. Direct Exact Substring Check
  const exactIdx = doc.fullText.indexOf(cleanedCandidate);
  if (exactIdx !== -1) {
    const matchedSection = findSectionForText(cleanedCandidate, doc);
    const startCtx = Math.max(0, exactIdx - 80);
    const endCtx = Math.min(doc.fullText.length, exactIdx + cleanedCandidate.length + 80);
    return {
      verified: true,
      matchType: 'EXACT_SUBSTRING',
      matchScore: 1.0,
      matchedLocation: matchedSection,
      matchedCharIndex: exactIdx,
      canonicalQuote: cleanedCandidate,
      surroundingContext: doc.fullText.slice(startCtx, endCtx),
      statusMessage: `Verified (100% Exact Match): Confirmed verbatim in ${matchedSection} (Offset #${exactIdx}).`,
    };
  }

  // 2. Normalized Verbatim Check (handles PDF linebreaks, multiple spaces, smart quotes)
  const normCandidate = normalizeTextForComparison(cleanedCandidate);
  for (const section of doc.sections) {
    const normSec = normalizeTextForComparison(section.content);
    const normIdx = normSec.indexOf(normCandidate);
    if (normIdx !== -1) {
      // Extract clean snippet from section
      const approxIdx = Math.max(
        0,
        Math.min(
          section.content.length - cleanedCandidate.length,
          Math.floor((normIdx / Math.max(1, normSec.length)) * section.content.length)
        )
      );
      const startCtx = Math.max(0, approxIdx - 60);
      const endCtx = Math.min(section.content.length, approxIdx + cleanedCandidate.length + 100);
      const globalOffset = Math.max(0, doc.fullText.indexOf(section.content.slice(0, 40)));

      return {
        verified: true,
        matchType: 'NORMALIZED_VERBATIM',
        matchScore: 0.97,
        matchedLocation: `${section.heading} (${section.pageOrFile})`,
        matchedCharIndex: globalOffset + approxIdx,
        canonicalQuote: cleanedCandidate,
        surroundingContext: section.content.slice(startCtx, endCtx),
        statusMessage: `Verified (97% Normalized Verbatim): Confirmed in ${section.heading} (${section.pageOrFile}).`,
      };
    }
  }

  // 3. Token Window Verification (checks if >= 88% of sequential words appear contiguously)
  const candTokens = normCandidate.split(/[^a-z0-9.]+/).filter((t) => t.length > 1);
  if (candTokens.length >= 5) {
    for (const section of doc.sections) {
      const secSentences = section.content
        .split(/(?<=[.!?])\s+|\n+/)
        .map((s) => s.trim())
        .filter((s) => s.length >= 20);

      for (const sentence of secSentences) {
        const sentNorm = normalizeTextForComparison(sentence);
        let hits = 0;
        for (const tok of candTokens) {
          if (sentNorm.includes(tok)) hits++;
        }
        const ratio = hits / candTokens.length;
        if (ratio >= 0.88) {
          const globalIdx = Math.max(0, doc.fullText.indexOf(sentence.slice(0, 25)));
          return {
            verified: true,
            matchType: 'NORMALIZED_VERBATIM',
            matchScore: Number(ratio.toFixed(2)),
            matchedLocation: `${section.heading} (${section.pageOrFile})`,
            matchedCharIndex: globalIdx,
            canonicalQuote: sentence, // Snap to exact verbatim sentence from paper!
            surroundingContext: sentence,
            statusMessage: `Verified (${(ratio * 100).toFixed(0)}% Token Snap): Calibrated to exact verbatim sentence in manuscript.`,
          };
        }
      }
    }
  }

  // 4. Failed Verification -> Discard Hallucination!
  return {
    verified: false,
    matchType: 'HALLUCINATION_REJECTED',
    matchScore: 0.21,
    matchedLocation: 'NOT_FOUND_IN_CORPUS',
    matchedCharIndex: -1,
    canonicalQuote: cleanedCandidate,
    surroundingContext: '',
    statusMessage: `Verification Failed (Hallucination Detected): Quote does not exist in the 1M-context corpus. Discarding and regenerating attack.`,
  };
}

function findSectionForText(snippet: string, doc: DocumentSource): string {
  for (const sec of doc.sections) {
    if (sec.content.includes(snippet)) {
      return `${sec.heading} (${sec.pageOrFile})`;
    }
  }
  return `Main Manuscript (${doc.sourceType})`;
}

/**
 * Automatically mines genuine verbatim sentences from an uploaded PDF or GitHub repo
 * for both:
 * 1) Fallback/re-rolled verified Reviewer 2 critiques (if an LLM candidate fails verification)
 * 2) Player's Manuscript Evidence Snippets extracted directly from their paper/repo!
 */
export interface ExtractedSentenceEvidence {
  quote: string;
  location: string;
  category: WeaknessCategory;
  suggestedAttackTitle: string;
  suggestedKoreanTitle: string;
  suggestedReviewerDialogue: string;
  suggestedEvidenceCardTitle: string;
}

export function mineGroundedSentencesFromDocument(doc: DocumentSource): ExtractedSentenceEvidence[] {
  const results: ExtractedSentenceEvidence[] = [];

  const patterns: Array<{
    category: WeaknessCategory;
    regex: RegExp;
    attackTitle: string;
    koreanTitle: string;
    dialogueBuilder: (quote: string) => string;
    cardTitle: string;
  }> = [
    {
      category: 'BASELINE',
      regex: /\b(table\s*\d+|baseline|compared\s+to|outperform|sota|state-of-the-art|benchmark|comparison)\b/i,
      attackTitle: 'Insufficient Baseline Selection',
      koreanTitle: 'Insufficient Baseline Selection',
      dialogueBuilder: () =>
        '"Are these the only baselines you bothered to include in this table? Did you conveniently omit modern competitive methods?"',
      cardTitle: 'Benchmark Comparison Log',
    },
    {
      category: 'ABLATION',
      regex: /\b(ablation|component|remove|without|w\/o|module|contribution|sensitivity|hyperparameter)\b/i,
      attackTitle: 'Incomplete Ablation & Component Isolation',
      koreanTitle: 'Incomplete Ablation & Component Isolation',
      dialogueBuilder: () =>
        '"The contribution of each individual module is completely opaque! How do you prove this hyperparameter isn\'t just overfitted?"',
      cardTitle: 'Ablation Study Log',
    },
    {
      category: 'STATISTICS',
      regex: /\b(\d+\.\d+%|\bp\s*[<>=]|variance|std|seed|average|mean|trials|accuracy|f1|bleu|latency|ms)\b/i,
      attackTitle: 'Statistical Significance & Variance Critique',
      koreanTitle: 'Statistical Significance & Variance Critique',
      dialogueBuilder: () =>
        '"Where are the confidence intervals and multi-seed variance? How do I know this metric isn\'t a lucky single-seed cherry-pick?!"',
      cardTitle: 'Multi-Seed Statistical Log',
    },
    {
      category: 'SCOPE',
      regex: /\b(limitation|future\s+work|assume|assumption|constraint|domain|scale|only|however)\b/i,
      attackTitle: 'Over-Generalization Beyond Tested Scope',
      koreanTitle: 'Over-Generalization Beyond Tested Scope',
      dialogueBuilder: () =>
        '"Your underlying assumptions are far too restrictive! Doesn\'t this entire pipeline collapse in real-world non-stationary settings?"',
      cardTitle: 'Scope & Fallback Design Log',
    },
    {
      category: 'REPRODUCIBILITY',
      regex: /\b(implementation|training|gpu|epoch|batch|learning\s+rate|config|code|github|docker|parameter)\b/i,
      attackTitle: 'Hidden Hyperparameter & Reproducibility Trap',
      koreanTitle: 'Hidden Hyperparameter & Reproducibility Trap',
      dialogueBuilder: () =>
        '"This looks heavily tuned to your specific hardware setup. Can an independent lab actually reproduce these numbers?"',
      cardTitle: 'Reproducibility & Code Log',
    },
    {
      category: 'NOVELTY',
      regex: /\b(propose|introduce|novel|first|architecture|framework|method|design|algorithm)\b/i,
      attackTitle: 'Incremental Novelty Critique ("A + B Paper")',
      koreanTitle: 'Incremental Novelty Critique ("A + B Paper")',
      dialogueBuilder: () =>
        '"This reads like a straightforward combination of existing techniques. What is the fundamental scientific novelty here?"',
      cardTitle: 'Core Architecture Definition',
    },
  ];

  for (const section of doc.sections) {
    const rawSentences = section.content
      .split(/(?<=[.!?])\s+|\n+/)
      .map((s) => s.trim())
      .filter((s) => s.length >= 32 && s.length <= 240);

    for (const sentence of rawSentences) {
      for (const pat of patterns) {
        if (pat.regex.test(sentence)) {
          const alreadyHas = results.some((r) => r.quote === sentence);
          if (!alreadyHas) {
            results.push({
              quote: sentence,
              location: `${section.heading} (${section.pageOrFile})`,
              category: pat.category,
              suggestedAttackTitle: pat.attackTitle,
              suggestedKoreanTitle: pat.koreanTitle,
              suggestedReviewerDialogue: pat.dialogueBuilder(sentence),
              suggestedEvidenceCardTitle: pat.cardTitle,
            });
          }
          break;
        }
      }
    }
  }

  // Fallback if document had unusual formatting: slice clean sentences
  if (results.length < 4) {
    const fallbackSentences = doc.fullText
      .split(/(?<=[.!?])\s+|\n+/)
      .map((s) => s.trim())
      .filter((s) => s.length >= 30 && s.length <= 210)
      .slice(0, 8);

    fallbackSentences.forEach((sent, idx) => {
      const pat = patterns[idx % patterns.length];
      results.push({
        quote: sent,
        location: doc.sections[0]
          ? `${doc.sections[0].heading} (${doc.sections[0].pageOrFile})`
          : 'Main Manuscript',
        category: pat.category,
        suggestedAttackTitle: pat.attackTitle,
        suggestedKoreanTitle: pat.koreanTitle,
        suggestedReviewerDialogue: pat.dialogueBuilder(sent),
        suggestedEvidenceCardTitle: pat.cardTitle,
      });
    });
  }

  return results;
}
